const words:Record<string,string>={
};
export function translate(value:string,language:AppLanguage){
 if(language!=='Hindi'||!value)return value;
 const clean=value.trim();const exact=phrases[clean.toLowerCase()];if(exact)return value.replace(clean,exact);
 // Keep title-cased API names such as airlines, hotel names, and city names as supplied.
 if(/^[A-Z][a-z]+(?:[ .'-]+[A-Z][a-z]+)+$/.test(clean))return value;
 return value.replace(/[A-Za-z]+(?:'[A-Za-z]+)?/g,word=>words[word.toLowerCase()]??word);
}
function localizeNode(node:React.ReactNode,language:AppLanguage):React.ReactNode{
 if(typeof node==='string')return translate(node,language);
 if(Array.isArray(node))return node.map(child=>localizeNode(child,language));
 if(React.isValidElement<{children?:React.ReactNode}>(node)&&node.props.children!==undefined)return React.cloneElement(node,{...node.props,children:localizeNode(node.props.children,language)});
 return node;
}
export const Text=forwardRef<React.ElementRef<typeof NativeText>,TextProps>(function LocalizedText({children,...props},ref){const{language}=useLocale();return <NativeText ref={ref} {...props} accessibilityLabel={props.accessibilityLabel?translate(props.accessibilityLabel,language):undefined}>{localizeNode(children,language)}</NativeText>;});
export const TextInput=forwardRef<React.ElementRef<typeof NativeTextInput>,TextInputProps>(function LocalizedTextInput(props,ref){const{language}=useLocale();return <NativeTextInput ref={ref} {...props} placeholder={props.placeholder?translate(props.placeholder,language):undefined} accessibilityLabel={props.accessibilityLabel?translate(props.accessibilityLabel,language):undefined}/>;});
