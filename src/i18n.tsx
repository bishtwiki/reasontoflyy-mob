export function I18nProvider({children}:{children:React.ReactNode}){
 const[language,setLanguageState]=useState<AppLanguage>('English');
 useEffect(()=>{void AsyncStorage.getItem('rtf-language').then(value=>{if(value==='Hindi'||value==='English')setLanguageState(value);}).catch(()=>{});},[]);
 const setLanguage=(value:AppLanguage)=>{setLanguageState(value);void AsyncStorage.setItem('rtf-language',value).catch(()=>{});};
 return <LocaleContext.Provider value={{language,setLanguage}}>{children}</LocaleContext.Provider>;
}
